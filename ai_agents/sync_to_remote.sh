#!/bin/bash
#
# 同步本地文件到远程服务器
# 使用方法: ./sync_to_remote.sh
#
# ========================================
# 配置区域 - 修改这里的配置
# ========================================

# 远程服务器连接信息 (格式: user@hostname 或 ~/.ssh/config 中的配置名)
REMOTE_HOST="zenking@192.168.8.233"

# 源目录 (本地)
LOCAL_DIR="/home/zj/ten-framework/ai_agents"

# 目标目录 (远程)
REMOTE_DIR="/data/metahuman_work/ten-framework/ai_agents"

# ========================================
# 同步规则配置
# ========================================
#
# 说明:
#   1. --include 参数指定要包含的文件模式
#   2. --exclude 参数指定要排除的文件模式
#   3. rsync 按照从上到下的顺序处理规则，第一个匹配的规则生效
#
# 添加新规则的步骤:
#   1. 在 RSYNC_INCLUDES 数组中添加要包含的文件模式
#   2. 如果需要排除特定文件，在 RSYNC_EXCLUDES 数组中添加排除模式
#
# 常用示例:
#   --include="*.py"           # 包含所有 .py 文件
#   --include="*.json"         # 包含所有 .json 文件
#   --include="docker-compose.yml"  # 包含特定文件
#   --include="dir/**"          # 包含整个目录及其内容
#   --include="dir/*.txt"       # 包含特定目录下的 .txt 文件
#   --exclude="*.log"           # 排除所有 .log 文件
#   --exclude="node_modules/"   # 排除 node_modules 目录
#

# ========================================
# 要包含的文件/目录模式 (按需添加)
# ========================================

RSYNC_INCLUDES=(
    # Python 文件
    "--include=*.py"

    # 配置文件
    "--include=docker-compose.yml"

    # ========================================
    # 在这里添加更多要同步的文件/目录
    # ========================================
    #
    # 示例:
    # "--include=*.json"              # 同步所有 JSON 文件
    # "--include=*.md"                # 同步所有 Markdown 文件
    # "--include=*.sh"                # 同步所有 Shell 脚本
    # "--include=agents/**/*.py"      # 同步 agents 目录下所有 py 文件
    # "--include=ten_packages/"       # 同步整个 ten_packages 目录
    # "--include=property.json"       # 同步特定文件
    # "--include=manifest.json"       # 同步特定文件
    #
    # ========================================
)

# ========================================
# 要排除的文件/目录模式 (按需添加)
# ========================================

RSYNC_EXCLUDES=(
    # 排除所有文件（然后通过 include 规则重新包含需要的文件）
    "--exclude=*"

    # ========================================
    # 在这里添加更多要排除的文件/目录
    # ========================================
    #
    # 示例:
    # "--exclude=*.log"               # 排除日志文件
    # "--exclude=__pycache__/"        # 排除 Python 缓存
    # "--exclude=*.pyc"               # 排除编译的 Python 文件
    # "--exclude=.git/"               # 排除 Git 目录
    # "--exclude=node_modules/"       # 排除 node_modules
    # "--exclude=msg_dict_json/"      # 排除特定目录
    #
    # ========================================
)

# ========================================
# rsync 选项
# ========================================

RSYNC_OPTIONS=(
    -a                      # 归档模式，保持文件属性
    -v                      # 详细输出
    -z                      # 压缩传输
    --delete                # 删除目标目录中源目录不存在的文件
    --progress              # 显示传输进度
    --stats                 # 显示传输统计信息
    --dry-run               # 预演模式，不实际执行（测试后注释掉此行）
)

# ========================================
# 执行同步
# ========================================

echo "=========================================="
echo "同步本地文件到远程服务器"
echo "=========================================="
echo "源目录: $LOCAL_DIR"
echo "目标:   $REMOTE_HOST:$REMOTE_DIR"
echo "=========================================="
echo ""

# 构建 rsync 命令
RSYNC_CMD=(
    rsync
    "${RSYNC_OPTIONS[@]}"
    "${RSYNC_EXCLUDES[@]}"
    "${RSYNC_INCLUDES[@]}"
    "$LOCAL_DIR/"
    "$REMOTE_HOST:$REMOTE_DIR/"
)

# 显示将要执行的命令
echo "执行命令:"
echo "${RSYNC_CMD[@]}"
echo ""
echo "=========================================="

# 执行同步
"${RSYNC_CMD[@]}"

# 检查执行结果
if [ $? -eq 0 ]; then
    echo ""
    echo "=========================================="
    echo "同步完成!"
    echo "=========================================="
else
    echo ""
    echo "=========================================="
    echo "同步失败，请检查错误信息"
    echo "=========================================="
    exit 1
fi
